#include <filesystem>
#include <fstream>
#include <iomanip>
#include <iostream>
#include "../Source/DSP/ElectryFx.cpp"

namespace electry
{
struct ElectryFxTestAccess
{
    static const auto& triodeTransfer() { return ElectryFx::triodeTransferTable(); }
};
}

namespace
{
template <typename T>
void value(std::ostream& stream, T number)
{
    stream << std::hexfloat << number;
    if constexpr (std::is_same<T, float>::value)
        stream << 'f';
}

template <typename Range, typename Writer>
void array(std::ostream& stream, const Range& range, Writer writer)
{
    stream << "{{\n";
    for (const auto& element : range)
    {
        writer(stream, element);
        stream << ",\n";
    }
    stream << "}}";
}

template <typename Range>
void scalars(std::ostream& stream, const Range& range)
{
    array(stream, range, [] (auto& out, const auto number) { value(out, number); });
}

void cubic(std::ostream& out, const electry::PhaseMathCubic& p)
{
    out << '{'; value(out, p.a); out << ','; value(out, p.b);
    out << ','; value(out, p.c); out << ','; value(out, p.d); out << '}';
}

template <typename Writer>
void file(const std::filesystem::path& directory, const char* name, Writer writer)
{
    std::ofstream stream(directory / (std::string(name) + ".inc"));
    if (!stream) throw std::runtime_error("Cannot create frozen data file");
    stream << "// Generated by Tools/generate_frozen_tables.py; do not edit.\n";
    writer(stream);
    stream << '\n';
    if (!stream) throw std::runtime_error("Cannot write frozen data file");
}
}

int main(int argc, char** argv)
{
    if (argc != 2) return 2;
    using namespace electry;
    const std::filesystem::path destination(argv[1]);
    std::filesystem::create_directories(destination);
    file(destination, "PhaseMath", [] (auto& out)
    {
        const auto& tables = phaseMathTables();
        out << "{\n";
        array(out, tables.soft, cubic);
        out << ",\n";
        array(out, tables.powers, [] (auto& stream, const auto& power)
        {
            stream << "{\n";
            array(stream, power.intervals, cubic);
            stream << ",\n"; scalars(stream, power.scale);
            stream << ",\n"; scalars(stream, power.slopeScale);
            stream << "\n}";
        });
        out << "\n}";
    });
    for (const auto model : { AmpModel::AmericanClean, AmpModel::BritishCrunch })
    {
        const bool british = model == AmpModel::BritishCrunch;
        file(destination, british ? "PhaseCalibrationEcc83" : "PhaseCalibrationEcc81",
             [model] (auto& out)
        {
            const auto& c = phaseInverterCalibration(model);
            out << "{{"; value(out, c.idle.plateOne);
            out << ','; value(out, c.idle.plateTwo);
            out << ','; value(out, c.idle.cathode);
            out << ','; value(out, c.idle.tail);
            out << ','; value(out, c.idle.totalCurrent);
            out << "},"; value(out, c.inputVoltsPerDrive); out << '}';
        });
        file(destination, british ? "PowerCalibrationEl34" : "PowerCalibration6L6",
             [model] (auto& out)
        {
            const auto& c = powerTubeCalibration(model);
            out << '{'; value(out, c.plateSwingPerDrive);
            out << ','; value(out, c.nominalIdleCurrent);
            out << ','; value(out, c.demandSpan); out << '}';
        });
        file(destination, british ? "PowerTableEl34" : "PowerTable6L6",
             [model] (auto& out)
        {
            const auto& table = powerTubeTable(model);
            out << "{\n";
            array(out, table.points, [] (auto& stream, const auto& point)
            {
                stream << '{'; value(stream, point.output);
                stream << ','; value(stream, point.supplyDemand); stream << '}';
            });
            out << ",\n"; value(out, table.idleDemandError); out << "\n}";
        });
    }
    file(destination, "PowerGrid", [] (auto& out)
    {
        scalars(out, powerGridCurrentTable());
    });
    file(destination, "TriodeTransfer", [] (auto& out)
    {
        scalars(out, ElectryFxTestAccess::triodeTransfer());
    });
}
